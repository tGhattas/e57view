import { chromium } from 'playwright';
const SCAN = '/Users/tamer/Downloads/1973-registered.e57';
const b = await chromium.launch({ channel: 'chrome', headless: false, args: ['--ignore-gpu-blocklist', '--enable-gpu'] });
const p = await (await b.newContext({ viewport: { width: 1340, height: 880 } })).newPage();
await p.goto('https://e57view.web.app/', { waitUntil: 'networkidle' });
await p.setInputFiles('#file-input', SCAN);
await p.waitForFunction(() => /loaded in/.test(document.getElementById('tb-points')?.textContent || ''), null, { timeout: 180000 });
console.log('loaded:', await p.evaluate(() => document.getElementById('tb-points').textContent));
const t0 = Date.now();
const r = await p.evaluate(() => window.__app.agentRun('analysis', { op: 'sor', neighbours: 6, nSigma: 1 }).then(v => ({ ok: true, v }), e => ({ ok: false, err: String(e?.message ?? e) })));
console.log('sor after', ((Date.now() - t0) / 1000).toFixed(1), 's ->', JSON.stringify(r).slice(0, 400));
console.log('points now:', await p.evaluate(() => document.getElementById('tb-points').textContent));
await b.close();
